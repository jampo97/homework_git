# Тест фильтра фильмов при вводе нормальных значений
@pytest.mark.parametrize(
    " my_filter, filtered",
    [
        (
            "EXECUTED",
            [
                {"id": 41428829, "state": "EXECUTED", "date": "2019-07-03T18:35:29.512364"},
                {"id": 939719570, "state": "EXECUTED", "date": "2018-06-30T02:08:58.425572"},
            ],
        ),
        (
            "CANCELED",
            [
                {"id": 594226727, "state": "CANCELED", "date": "2018-09-12T21:27:25.241689"},
                {"id": 615064591, "state": "CANCELED", "date": "2018-10-14T08:21:33.419441"},
            ],
        ),
        (
            None,
            [
                {"id": 41428829, "state": "EXECUTED", "date": "2019-07-03T18:35:29.512364"},
                {"id": 939719570, "state": "EXECUTED", "date": "2018-06-30T02:08:58.425572"},
            ],
        ),
    ],
)
def test_filter_by_state(example_my: list[dict], my_filter: str, filtered: list[dict]) -> None:
    assert filter_by_state(example_my, my_filter) == filtered


# Тест сортировки даты при нормальном вводе
def test_sort_by_date(example_my: list[dict], sorted_date_up: list[dict], sorted_date_down: list[dict]) -> None:
    assert sort_by_date(example_my, True) == sorted_date_up
    assert sort_by_date(example_my, False) == sorted_date_down
    assert sort_by_date(example_my, None) == sorted_date_up
